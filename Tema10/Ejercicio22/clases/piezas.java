package Tema10.Ejercicio22.clases;

public class piezas {
    
    private String nombre;
    private int valor;

    public piezas(String nombre, int valor){
        this.nombre = nombre;
        this.valor = valor;
    }

    public String getNombre() {
        return nombre;
    }

    public int getValor() {
        return valor;
    }
}
